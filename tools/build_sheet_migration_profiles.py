"""Build the offline blank-sheet fingerprints used by the character migration page."""
import argparse
import base64
import io
import json
import posixpath
import re
import unicodedata
import xml.etree.ElementTree as ET
from hashlib import sha256
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo


def fingerprint(data):
    value = 2166136261
    for byte in data:
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return str(value)


def string_value(node):
    if node is None:
        return ''
    return ''.join(t.text or '' for child in node for t in
                   ([child] if child.tag.endswith('}t') else child.findall('{*}t') if child.tag.endswith('}r') else []))


def cell_token(cell, strings):
    if cell.find('{*}f') is not None:
        return 'f'
    kind, value = cell.get('t', 'n'), cell.findtext('{*}v', '')
    if kind in ('s', 'inlineStr', 'str'):
        if kind == 's':
            value = strings[int(value)] if value else ''
        elif kind == 'inlineStr':
            value = string_value(cell.find('{*}is'))
        return 's' + fingerprint(value.encode()) if value else None
    if not value:
        return None
    if kind == 'n' and float(value).is_integer():
        value = str(int(float(value)))
    return kind + value


def pack(root, output):
    sheets, portraits, seen = {}, set(), set()
    files = sorted((root/'resources/sheets').glob('character*.xlsx'))
    files += sorted((root/'archive/rw-original/sheet').rglob('character*.xlsx'))
    if not files:
        raise ValueError('No PC templates found')
    for path in files:
        digest = sha256(path.read_bytes()).digest()
        if digest in seen:
            continue
        seen.add(digest)
        with ZipFile(path) as book:
            wb = ET.fromstring(book.read('xl/workbook.xml'))
            rels = {r.get('Id'): r.get('Target') for r in ET.fromstring(book.read('xl/_rels/workbook.xml.rels'))}
            strings = [string_value(si) for si in ET.fromstring(book.read('xl/sharedStrings.xml'))]
            for sheet in wb.find('{*}sheets'):
                name = re.sub(r'\s+', '', unicodedata.normalize('NFKC', sheet.get('name')))
                if name in {'リスト', '互換リスト', '計算用', 'コピペ用'}:
                    continue
                target = rels[sheet.get('{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id')]
                part = posixpath.normpath(posixpath.join('xl', target)).lstrip('/')
                xml = ET.fromstring(book.read(part))
                cells = {}
                for cell in xml.iterfind('{*}sheetData/{*}row/{*}c'):
                    value = cell_token(cell, strings)
                    if value is not None:
                        cells[cell.get('r')] = value
                merges = sorted(m.get('ref') for m in xml.iterfind('{*}mergeCells/{*}mergeCell'))
                profile = {'shape': fingerprint(','.join(merges).encode()), 'cells': cells}
                variants = sheets.setdefault(name, [])
                if profile not in variants:
                    variants.append(profile)
            for media in book.namelist():
                if media.startswith('xl/media/'):
                    portraits.add(fingerprint(book.read(media)))
    data = json.dumps({'sheets': sheets, 'stockImages': sorted(portraits)}, separators=(',', ':'), ensure_ascii=False)
    payload = io.BytesIO()
    with ZipFile(payload, 'w') as archive:
        archive.writestr(ZipInfo('profiles.json'), data.encode(), compress_type=ZIP_DEFLATED, compresslevel=9)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('// Generated by tools/build_sheet_migration_profiles.py\nconst blankSheetProfiles = "' +
                      base64.b64encode(payload.getvalue()).decode() + '";\n', encoding='ascii')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    pack(args.root, args.output or args.root/'assets/sheet-migration/profiles.js')
